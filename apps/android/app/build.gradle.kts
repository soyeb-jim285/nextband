// Demo mode: ship the iOS demo fixtures (apps/ios/IELTS/Demo/fixtures.json, generated by apps/ios/scripts/gen-demo-fixtures.mjs)
// as the asset `fixtures.json`. One source of truth for both apps.
abstract class CopyDemoFixtures : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val source: RegularFileProperty
    /** The map figure of the Listening & Reading fixtures (served for the placeholder image URL). */
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val map: RegularFileProperty
    @get:OutputDirectory abstract val outDir: DirectoryProperty

    @TaskAction fun copy() {
        source.get().asFile.copyTo(outDir.get().file("fixtures.json").asFile, overwrite = true)
        map.get().asFile.copyTo(outDir.get().file("demo-map.png").asFile, overwrite = true)
    }
}

val copyDemoFixtures by tasks.registering(CopyDemoFixtures::class) {
    source.set(rootProject.layout.projectDirectory.file("../ios/IELTS/Demo/fixtures.json"))
    map.set(rootProject.layout.projectDirectory.file("../ios/IELTS/Demo/demo-map.png"))
}

tasks.matching { it.name == "bundleRelease" }.configureEach {
    val signed = storeSigned
    val web = channel == "web"
    doFirst {
        if (!signed) throw GradleException("bundleRelease needs the upload key: set NEXTBAND_KEYSTORE, NEXTBAND_KEYSTORE_PASSWORD, NEXTBAND_KEY_ALIAS, NEXTBAND_KEY_PASSWORD.")
        if (web) throw GradleException("bundleRelease is the Play artifact: build it with nextband.channel=play (the web channel sells in the app).")
    }
}

// The web-channel APK is what nextband.app hands out: never debug-signed (public key, demo mode on). Unsigned release APKs are play-channel test builds.
tasks.matching { it.name == "packageRelease" || it.name == "assembleRelease" }.configureEach {
    val signed = storeSigned
    val web = channel == "web"
    doFirst {
        if (web && !signed) throw GradleException("The web-channel release APK needs the release key: set NEXTBAND_KEYSTORE, NEXTBAND_KEYSTORE_PASSWORD, NEXTBAND_KEY_ALIAS, NEXTBAND_KEY_PASSWORD.")
    }
}

androidComponents {
    onVariants { variant -> variant.sources.assets?.addGeneratedSourceDirectory(copyDemoFixtures, CopyDemoFixtures::outDir) }
}

